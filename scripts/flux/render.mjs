#!/usr/bin/env node
// LAST LIGHT — render art assets one by one with Cloudflare Workers AI (Flux).
//
//   NODE_USE_ENV_PROXY=1 node scripts/flux/render.mjs [--max N] [--only key[,key]] [--retry-flagged] [--dry]
//
// Env: CLOUDFLARE_API_TOKEN (Workers AI Read+Edit), CLOUDFLARE_ACCOUNT_ID (optional:
// the first account the token can see is used). In a Claude Code cloud session the
// egress proxy injects the token, so the variable may be left unset.
//
// After EVERY asset the status is written to scripts/flux/manifest.json and the
// human tracker docs/ASSETS.md is regenerated, so an interrupted run loses nothing.
// The run stops on the daily free-allocation limit (Workers AI error 3036) and exits
// with code 3, so a wrapper can commit what was rendered.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync, statSync, rmSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { ASSETS } from './prompts.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const GEN = join(ROOT, 'src', 'art', 'gen');
const MANIFEST = join(HERE, 'manifest.json');
const TRACKER = join(ROOT, 'docs', 'ASSETS.md');
const MODEL = '@cf/black-forest-labs/flux-2-klein-4b';
const API = 'https://api.cloudflare.com/client/v4';
const TOKEN = process.env.CLOUDFLARE_API_TOKEN || 'proxy-injected';

const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const opt = (f) => (args.includes(f) ? args[args.indexOf(f) + 1] : undefined);
const MAX = Number(opt('--max') ?? Infinity);
const ONLY = opt('--only')?.split(',');
const RETRY_FLAGGED = flag('--retry-flagged');
const DRY = flag('--dry');
const FORCE = flag('--force'); // with --only: re-render keys even if already done

// klein-4b lists ≈26.05 neurons per 512×512 output tile, but account analytics for the
// first run (139 calls, 13,859 neurons) show every image billed as at least 4 tiles
// (~104 neurons), whatever its size. Free tier: 10,000/day, so ~95 images a day.
const tiles = (a) => Math.max(4, Math.ceil(a.w / 512) * Math.ceil(a.h / 512));
const neurons = (a) => Math.round(tiles(a) * 26.05);

const LABEL = { backdrop: 'Location backdrops', portrait: 'Portraits', still: 'Card stills', icon: 'Map node icons', item: 'Item icons', symbol: 'Stat symbols' };

function loadManifest() {
  const m = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : {};
  m.model = MODEL;
  m.assets ??= {};
  for (const a of ASSETS) m.assets[a.key] ??= { status: 'pending' };
  return m;
}

function save(m) {
  const ordered = {};
  for (const a of ASSETS) ordered[a.key] = m.assets[a.key];
  m.assets = ordered;
  writeFileSync(MANIFEST, JSON.stringify(m, null, 1) + '\n');
  writeFileSync(TRACKER, tracker(m));
}

function tracker(m) {
  const by = {};
  for (const a of ASSETS) (by[a.cls] ??= []).push(a);
  const st = (a) => m.assets[a.key].status;
  const done = ASSETS.filter((a) => st(a) === 'done');
  const left = ASSETS.filter((a) => st(a) !== 'done');
  const L = [];
  L.push('# Art assets: Flux conversion tracker', '');
  L.push(
    `Every procedural SVG asset in \`src/art/\`, and its painted replacement rendered with Cloudflare Workers AI \`${MODEL}\`.`,
    'The game uses a painted image as soon as its file exists in `src/art/gen/` and falls back to the SVG art otherwise (see `src/art/gen.ts`), so a partly converted set ships safely.',
    '',
    'This file is regenerated by `scripts/flux/render.mjs` after every asset. Edit prompts in `scripts/flux/prompts.mjs`.',
    '',
  );
  L.push(`**${done.length} / ${ASSETS.length} converted.** About ${left.reduce((s, a) => s + neurons(a), 0).toLocaleString('en-US')} neurons of work left (free tier: 10,000 a day, reset 00:00 UTC).`);
  if (m.lastRun) L.push('', `Last run: ${m.lastRun.at}, ${m.lastRun.rendered} rendered, stopped because: ${m.lastRun.stop}.`);
  L.push('', '| Class | Done | Total | Render size | Stored size | Neurons each |', '| --- | ---: | ---: | --- | --- | ---: |');
  for (const [cls, list] of Object.entries(by)) {
    const a = list[0];
    L.push(`| ${LABEL[cls]} | ${list.filter((x) => st(x) === 'done').length} | ${list.length} | ${a.w}×${a.h} | ${a.out[0]}×${a.out[1]} WebP | ~${neurons(a)} |`);
  }
  L.push('', 'Status: ✅ done · ⬜ pending · 🚩 flagged by the model\'s output filter (reword the prompt and rerun with `--retry-flagged`) · ❌ error');
  const icon = { done: '✅', pending: '⬜', flagged: '🚩', error: '❌' };
  for (const [cls, list] of Object.entries(by)) {
    L.push('', `## ${LABEL[cls]}`, '', '| | Asset | Preview | Rendered |', '| --- | --- | --- | --- |');
    for (const a of list) {
      const s = m.assets[a.key];
      const prev = s.status === 'done' ? `<img src="../src/art/gen/${a.key}.webp" height="48">` : '';
      L.push(`| ${icon[s.status] ?? '⬜'} | \`${a.key}\` | ${prev} | ${s.renderedAt ? s.renderedAt.slice(0, 16).replace('T', ' ') : s.error ? s.error.slice(0, 60) : ''} |`);
    }
  }
  return L.join('\n') + '\n';
}

async function accountId() {
  if (process.env.CLOUDFLARE_ACCOUNT_ID) return process.env.CLOUDFLARE_ACCOUNT_ID;
  const r = await fetch(`${API}/accounts?per_page=1`, { headers: { Authorization: `Bearer ${TOKEN}` } });
  const j = await r.json();
  if (!j.success || !j.result?.length) throw new Error(`Cannot list accounts: ${JSON.stringify(j.errors)}`);
  return j.result[0].id;
}

async function run(acc, a) {
  const form = new FormData();
  form.append('prompt', a.prompt);
  form.append('width', String(a.w));
  form.append('height', String(a.h));
  const r = await fetch(`${API}/accounts/${acc}/ai/run/${MODEL}`, { method: 'POST', headers: { Authorization: `Bearer ${TOKEN}` }, body: form });
  let j;
  try {
    j = await r.json();
  } catch {
    return { http: r.status, code: 0, message: `non-JSON response (HTTP ${r.status})` };
  }
  if (j.success && j.result?.image) return { image: j.result.image };
  const e = j.errors?.[0] ?? {};
  return { http: r.status, code: e.code ?? 0, message: e.message ?? JSON.stringify(j).slice(0, 200) };
}

function store(a, b64) {
  const out = join(GEN, `${a.key}.webp`);
  mkdirSync(dirname(out), { recursive: true });
  const tmp = join(tmpdir(), `flux-${process.pid}.jpg`);
  writeFileSync(tmp, Buffer.from(b64, 'base64'));
  const [w, h] = a.out;
  execFileSync('convert', [tmp, '-resize', `${w}x${h}^`, '-gravity', 'center', '-extent', `${w}x${h}`, '-strip', '-quality', a.cls === 'icon' || a.cls === 'item' || a.cls === 'symbol' ? '82' : '78', out]);
  rmSync(tmp, { force: true });
  return { file: relative(ROOT, out), bytes: statSync(out).size };
}

const isLimit = (r) => r.code === 3036 || r.code === 4006 || (r.http === 429 && /daily|allocation|neuron/i.test(r.message));
const isBusy = (r) => r.code === 3040 || (r.http === 429 && !isLimit(r)) || r.http >= 500;
const isFlagged = (r) => r.code === 3030 || /flagged/i.test(r.message);

async function main() {
  const m = loadManifest();
  save(m);
  const queue = ASSETS.filter((a) => {
    if (ONLY && !ONLY.includes(a.key)) return false;
    const s = m.assets[a.key].status;
    return s === 'pending' || s === 'error' || (s === 'flagged' && (RETRY_FLAGGED || ONLY)) || (s === 'done' && FORCE && ONLY);
  }).slice(0, MAX);
  console.log(`${queue.length} to render (~${queue.reduce((s, a) => s + neurons(a), 0)} neurons).`);
  if (DRY) return;
  const acc = await accountId();
  let rendered = 0;
  let fails = 0;
  let stop = 'queue finished';
  for (const a of queue) {
    let r;
    for (let attempt = 1; attempt <= 4; attempt++) {
      r = await run(acc, a);
      if (!isBusy(r)) break;
      console.log(`  busy (${r.code || r.http}), retrying in ${attempt * 10}s`);
      await new Promise((res) => setTimeout(res, attempt * 10_000));
    }
    const s = m.assets[a.key];
    s.attempts = (s.attempts ?? 0) + 1;
    if (r.image) {
      Object.assign(s, { status: 'done', ...store(a, r.image), renderedAt: new Date().toISOString() });
      delete s.error;
      rendered++;
      fails = 0;
      console.log(`✅ ${a.key} (${s.bytes} B)`);
    } else if (isLimit(r)) {
      stop = `daily neuron limit (${r.code}: ${r.message})`;
      console.log(`⛔ ${stop}`);
      break;
    } else if (isFlagged(r)) {
      Object.assign(s, { status: 'flagged', error: `${r.code}: output flagged` });
      console.log(`🚩 ${a.key} flagged`);
    } else {
      Object.assign(s, { status: 'error', error: `${r.code || r.http}: ${r.message}` });
      console.log(`❌ ${a.key} ${s.error}`);
      if (++fails >= 5) {
        stop = `5 errors in a row (last: ${s.error})`;
        save(m);
        break;
      }
    }
    save(m); // mark + update the tracker immediately after each asset
  }
  m.lastRun = { at: new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC', rendered, stop };
  save(m);
  console.log(`Done: ${rendered} rendered. Stop: ${stop}`);
  if (stop.startsWith('daily')) process.exitCode = 3;
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
